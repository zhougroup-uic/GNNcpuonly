#!/usr/bin/env python
"""Generate the slim inference core from an unmodified clone of GreenleafLab/nnn_paper.

  python mk_core.py --clone nnn_paper --out .

Writes
  gnn_core.py       graph builder + GNN class, extracted verbatim (via ast) from nnn_paper/nnn/gnn.py
                    (nnn_paper is MIT licensed, (c) 2025 Yuxi; see NOTICE.md). No scipy, sklearn,
                    matplotlib, seaborn or wandb are needed to import it.
  train_stats.json  dH/Tm min/max/mean/std of the training split (the model outputs are min-max
                    normalised with these) and the training sequence-length range.
"""
import argparse
import ast
import json
from pathlib import Path

import numpy as np
import pandas as pd

WANT = ["dotbracket2edgelist", "onehot_nucleotide", "norm_p", "unorm_p",
        "calc_sumstats", "row2graphdata", "unorm", "GNN"]

HEAD = '''"""Slim inference core, extracted verbatim (functions/class) from GreenleafLab/nnn_paper nnn/gnn.py
(MIT licence, (c) 2025 Yuxi). Only what is needed to build graphs and run the saved GNN: no scipy, sklearn,
matplotlib, seaborn or wandb. Generated by mk_core.py; do not edit."""
import numpy as np
import pandas as pd
import torch
import torch.nn.functional as F
from torch import nn
from torch.nn import Linear, BatchNorm1d, Sequential, ModuleList
from torch_geometric.data import Data
from torch_geometric.nn import GCNConv, GINConv, GATv2Conv, BatchNorm, TransformerConv
from torch_geometric.nn import global_mean_pool, global_add_pool
from torch_geometric.nn.aggr import Set2Set


'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--clone", default="nnn_paper", help="path of the nnn_paper clone")
    ap.add_argument("--out", default=".", help="where to write gnn_core.py and train_stats.json")
    a = ap.parse_args()
    clone, out = Path(a.clone), Path(a.out)

    src = (clone / "nnn" / "gnn.py").read_text()
    chunks = {n.name: ast.get_source_segment(src, n)
              for n in ast.parse(src).body
              if isinstance(n, (ast.FunctionDef, ast.ClassDef)) and n.name in WANT}
    missing = set(WANT) - set(chunks)
    if missing:
        raise SystemExit(f"not found in {clone}/nnn/gnn.py: {sorted(missing)} (unexpected nnn_paper version?)")
    (out / "gnn_core.py").write_text(HEAD + "\n\n\n".join(chunks[k] for k in WANT) + "\n")

    raw = clone / "data" / "models" / "raw"
    arr = pd.read_csv(raw / "combined_dataset.csv").set_index("SEQID")
    split = json.load(open(raw / "combined_data_split.json"))
    tr = arr.loc[split["train_ind"]]
    ss = {f"{p}_{k}": float(f(tr[p])) for p in ("dH", "Tm")
          for k, f in (("mean", np.nanmean), ("std", np.nanstd), ("min", np.nanmin), ("max", np.nanmax))}
    lens = tr.RefSeq.str.len()
    json.dump(dict(sumstats=ss, len_min=int(lens.min()), len_max=int(lens.max()),
                   note="from data/models/raw/combined_dataset.csv rows listed in train_ind of combined_data_split.json"),
              open(out / "train_stats.json", "w"), indent=1)
    print(f"wrote {out/'gnn_core.py'} ({len(chunks)} objects) and {out/'train_stats.json'} "
          f"(train n={len(tr)}, length {lens.min()}-{lens.max()} nt)")


if __name__ == "__main__":
    main()
